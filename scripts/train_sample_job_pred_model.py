#!/usr/bin/env python3
"""
scripts/train_sample_job_pred_model.py — trains a SAMPLE job-prediction
model from fabricated synthetic data, for src/job_pred/model_data/.

NOT trained on real Frontier telemetry. This repo ships no raw or
aggregate Frontier measurements for job prediction (see
scripts/build_placeholder_job_stats.py's docstring for the related
stats.json story) — the training rows here are generated by simple,
documented formulas below (base wattage per component + a GPU/CPU
multiplier + a small per-domain jitter + noise), not fit to or derived
from any real dataset. Predictions from this model are illustrative only:
plausible-looking numbers with the right shape and scale, not forecasts
anyone should act on. Swap in a model trained on real data before using
this for anything operational.

Produces the exact artifact set src/job_pred/regression.py's inference
code expects (see REQUIRED_MODEL_FILES there): encoder.joblib,
input_scalers.joblib, output_scalers.joblib, decision_tree.joblib,
model_latest.pth. Schema (input/output columns, categorical encoding,
scaler shapes) matches src/job_pred/regression.py's jobstat_inference()
exactly — verified by this script running real jobstat_inference() calls
against its own output before declaring success.

Usage:
    .venv/bin/python scripts/train_sample_job_pred_model.py
"""
from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

import joblib
import numpy as np
import torch
import torch.nn as nn
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.tree import DecisionTreeRegressor

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.job_pred.model import RegressionModel
from src.job_pred.regression import (
    ENCODER_FILENAME, INPUT_SCALERS_FILENAME, OUTPUT_SCALERS_FILENAME,
    DECISION_TREE_FILENAME, MODEL_FILENAME, TEST_LOSS_FILENAME, model_data_dir,
)

RNG = np.random.default_rng(1234)  # fixed seed: reproducible, not hiding anything

NUMERICAL_COLS = ["time_elapsed", "node_count"]
CATEGORICAL_COLS = ["utilization_type", "domain"]
# Must match src/job_pred/regression.py's jobstat_inference() exactly —
# order and names, not just the set.
OUTPUT_COLS = [
    "stats_node_power_node_max", "stats_node_power_node_mean",
    "stats_node_power_node_stddev", "stats_cpu_memory_power_node_max",
    "stats_gpu_power_node_max", "stats_gpu_power_node_mean",
    "stats_gpu_power_node_stddev", "stats_node_temp_node_max",
    "stats_node_temp_node_stddev", "stats_total_node_energy",
    "stats_total_node_energy_node_max", "stats_total_node_energy_node_mean",
    "stats_total_cpu_memory_energy", "stats_total_gpu_energy",
    "stats_total_gpu_energy_node_max", "stats_total_gpu_energy_node_mean",
]

DOMAINS_CSV = Path(__file__).resolve().parent.parent / "src/site/ornl/frontier/metadata/desc_science_domains.csv"


def _real_domain_codes() -> list[str]:
    with DOMAINS_CSV.open() as f:
        return [row["Domain"] for row in csv.DictReader(f)]


def _domain_jitter(domain: str) -> float:
    """Deterministic per-domain multiplier in [0.85, 1.15] — some science
    domains run moderately more GPU/compute-intensive codes than others,
    which is physically reasonable as flavor, but the actual spread here
    is arbitrary (hashed from the domain code), not measured."""
    h = int(hashlib.sha256(domain.encode()).hexdigest()[:8], 16)
    return 0.85 + 0.30 * (h / 0xFFFFFFFF)


def _synthesize_row(domain: str, node_count: int, time_elapsed: int, utilization_type: str) -> dict:
    """One fabricated but self-consistent training row. Base wattages are
    plausible orders of magnitude for a GPU-accelerated HPC node (not
    measured); gpu_frac models a CPU-only job still drawing idle GPU power
    rather than exactly zero."""
    jitter = _domain_jitter(domain)
    gpu_frac = 1.0 if utilization_type == "gpu" else 0.08
    size_decay = 1.0 - 0.015 * np.log10(node_count + 1)  # mild: big jobs sync overhead

    cpu_power = 220 * jitter
    mem_power = 65 * jitter
    gpu_power = 480 * gpu_frac * jitter
    node_power_mean = (50 + cpu_power + mem_power + gpu_power) * size_decay
    node_power_max = node_power_mean * RNG.uniform(1.15, 1.35)
    node_power_stddev = node_power_mean * RNG.uniform(0.05, 0.15)
    cpu_mem_power_max = mem_power * RNG.uniform(1.1, 1.3)
    gpu_power_max = gpu_power * RNG.uniform(1.1, 1.3) if gpu_power > 1 else RNG.uniform(5, 15)
    gpu_power_stddev = gpu_power * RNG.uniform(0.05, 0.2) if gpu_power > 1 else RNG.uniform(0.5, 2)

    node_temp_max = 45 + 25 * gpu_frac + RNG.uniform(-3, 3)
    node_temp_stddev = RNG.uniform(1.5, 5)

    # Energy = power * time, plus noise. "_node_max"/"_node_mean" are
    # per-node (independent of node_count); the bare total is summed
    # across every node the job used.
    noise = lambda: RNG.uniform(0.9, 1.1)
    total_node_energy_per_node_mean = node_power_mean * time_elapsed * noise()
    total_node_energy_per_node_max = total_node_energy_per_node_mean * RNG.uniform(1.1, 1.3)
    total_node_energy = total_node_energy_per_node_mean * node_count * noise()
    total_cpu_mem_energy = mem_power * time_elapsed * noise()
    total_gpu_energy_per_node_mean = gpu_power * time_elapsed * noise()
    total_gpu_energy_per_node_max = total_gpu_energy_per_node_mean * RNG.uniform(1.1, 1.3)
    total_gpu_energy = total_gpu_energy_per_node_mean * node_count * noise()

    return {
        "stats_node_power_node_max": node_power_max,
        "stats_node_power_node_mean": node_power_mean,
        "stats_node_power_node_stddev": node_power_stddev,
        "stats_cpu_memory_power_node_max": cpu_mem_power_max,
        "stats_gpu_power_node_max": gpu_power_max,
        "stats_gpu_power_node_mean": gpu_power,
        "stats_gpu_power_node_stddev": gpu_power_stddev,
        "stats_node_temp_node_max": node_temp_max,
        "stats_node_temp_node_stddev": node_temp_stddev,
        "stats_total_node_energy": total_node_energy,
        "stats_total_node_energy_node_max": total_node_energy_per_node_max,
        "stats_total_node_energy_node_mean": total_node_energy_per_node_mean,
        "stats_total_cpu_memory_energy": total_cpu_mem_energy,
        "stats_total_gpu_energy": total_gpu_energy,
        "stats_total_gpu_energy_node_max": total_gpu_energy_per_node_max,
        "stats_total_gpu_energy_node_mean": total_gpu_energy_per_node_mean,
    }


def build_dataset(n_rows: int) -> tuple[list[dict], np.ndarray]:
    domains = _real_domain_codes()
    inputs = []
    outputs = np.zeros((n_rows, len(OUTPUT_COLS)))
    for i in range(n_rows):
        domain = RNG.choice(domains)
        node_count = int(np.clip(10 ** RNG.uniform(0, np.log10(9408)), 1, 9408))
        time_elapsed = int(np.clip(10 ** RNG.uniform(np.log10(60), np.log10(86400)), 60, 86400))
        utilization_type = RNG.choice(["cpu", "gpu"])
        row = _synthesize_row(domain, node_count, time_elapsed, utilization_type)
        inputs.append({
            "domain": domain, "node_count": node_count,
            "time_elapsed": time_elapsed, "utilization_type": utilization_type,
        })
        outputs[i] = [row[c] for c in OUTPUT_COLS]
    return inputs, outputs


def encode_inputs(inputs: list[dict], encoder: OneHotEncoder) -> np.ndarray:
    cat = encoder.transform([[r[c] for c in CATEGORICAL_COLS] for r in inputs])
    num = np.array([[r[c] for c in NUMERICAL_COLS] for r in inputs], dtype=float)
    return np.concatenate([num, cat], axis=1)


def train_pt_model(X: np.ndarray, y: np.ndarray, epochs: int = 150) -> tuple[RegressionModel, float]:
    n = len(X)
    n_val = max(1, n // 10)
    idx = RNG.permutation(n)
    train_idx, val_idx = idx[n_val:], idx[:n_val]

    Xt = torch.tensor(X[train_idx], dtype=torch.float32)
    yt = torch.tensor(y[train_idx], dtype=torch.float32)
    Xv = torch.tensor(X[val_idx], dtype=torch.float32)
    yv = torch.tensor(y[val_idx], dtype=torch.float32)

    model = RegressionModel(X.shape[1], y.shape[1])
    opt = torch.optim.Adam(model.parameters(), lr=1e-3)
    loss_fn = nn.MSELoss()

    for epoch in range(epochs):
        model.train()
        opt.zero_grad()
        pred = model(Xt)
        loss = loss_fn(pred, yt)
        loss.backward()
        opt.step()

    model.eval()
    with torch.no_grad():
        val_loss = loss_fn(model(Xv), yv).item()
    return model, val_loss


def main() -> int:
    print("Synthesizing training data (fabricated, not real Frontier telemetry)...")
    inputs, y_raw = build_dataset(n_rows=6000)

    domains = _real_domain_codes()
    encoder = OneHotEncoder(
        categories=[["cpu", "gpu"], domains],
        sparse_output=False, handle_unknown="ignore",
    )
    encoder.fit([[r["utilization_type"], r["domain"]] for r in inputs])

    input_scalers = {}
    for col in NUMERICAL_COLS:
        scaler = StandardScaler()
        values = np.array([[r[col]] for r in inputs], dtype=float)
        scaler.fit(values)
        input_scalers[col] = scaler

    X_raw = encode_inputs(inputs, encoder)
    # Scale the numerical columns in place (categorical one-hot columns stay 0/1).
    X_scaled = X_raw.copy()
    for i, col in enumerate(NUMERICAL_COLS):
        X_scaled[:, i] = input_scalers[col].transform(X_raw[:, i].reshape(-1, 1)).ravel()

    output_scaler = StandardScaler()
    y_scaled = output_scaler.fit_transform(y_raw)

    print("Training PyTorch regression model...")
    model, val_loss = train_pt_model(X_scaled, y_scaled)
    print(f"  validation MSE (scaled space): {val_loss:.4f}")

    print("Training decision tree...")
    tree = DecisionTreeRegressor(max_depth=12, min_samples_leaf=5, random_state=1234)
    tree.fit(X_scaled, y_scaled)

    model_data_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(encoder, ENCODER_FILENAME)
    joblib.dump(input_scalers, INPUT_SCALERS_FILENAME)
    joblib.dump(output_scaler, OUTPUT_SCALERS_FILENAME)
    joblib.dump(tree, DECISION_TREE_FILENAME)
    torch.save(model.state_dict(), MODEL_FILENAME)
    TEST_LOSS_FILENAME.write_text(
        f"{val_loss}\n# Sample model trained on fabricated synthetic data "
        f"(scripts/train_sample_job_pred_model.py) -- NOT real Frontier telemetry.\n"
    )
    print(f"Wrote model artifacts to {model_data_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
